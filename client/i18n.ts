export function translate(language: Language, text: string, values?: Record<string, string | number>) {
  if (language === "en") return text;
  const message = ZH[text];
  let result = typeof message === "function" ? message(values?.value ?? "") : message ?? text;
  for (const [key, value] of Object.entries(values ?? {})) result = result.replace(`{${key}}`, String(value));
  return result;
}
